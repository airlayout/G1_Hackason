#!/usr/bin/env bash
# 実演1 — 純正リモコンで G1 を立たせて歩かせる。
#
#   bash Demo/01_remote.sh
#
# **この実演に PC は要らない。** 触るのはリモコンだけ。
# このスクリプトは順番を 1 つずつ出して、押したら Enter を待つだけの読み上げ係。
# 慌てて次へ行かないための道具なので、慣れていれば見なくてよい。
#
# ## なぜ順番が要るのか
#
# G1 は電源を入れた直後、関節が**ゼロトルク**（FSM 0）で脱力している。
# いきなり立たせようとしても効かず、吊り下げから外すと崩れる。
# ダンピング → 立位ロック → 通常運転 と 1 段ずつ上げる。
#
# ⚠️ **ダンピングはリモコンでしか入れられない。**
#    指令メッセージの motor_cmd[].mode=1 では有効にならない
#    （Teleop/vendor/g1-starter-kit/docs/06-troubleshooting.md）。
#    実演4 のテレオペで「送信は成功するのに腕が 1 mm も動かない」のはこれが原因。
set -eo pipefail

source "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/lib.sh"

step() {
    printf '\n\033[1m── %s ──\033[0m\n' "$1"
    shift
    for line in "$@"; do printf '   %b\n' "${line}"; done
    printf '\n   \033[2m済んだら Enter\033[0m '
    read -r _
}

_head "実演1 — リモコンで立たせて歩かせる"
cat <<'GUIDE'
   PC は使いません。リモコンだけです。

   ⚠️ 安全
      ・可動範囲に人と物が無いことを確認する
      ・電源を切れる位置に手が届く状態で操作する
      ・初めてのときは 2 人以上で。片方が吊り具に手をかける
GUIDE
printf '\n   \033[2m始めるなら Enter（やめるなら Ctrl-C）\033[0m '
read -r _

step "1. ウィンチで吊り上げる" \
     "G1 を吊り具で持ち上げ、\033[1m足が床から浮いた状態\033[0mにする。" \
     "立ち上がりの途中で崩れても倒れないようにするため。" \
     "床に着けたまま次へ進まないこと。"

step "2. 電源を入れ、Zero Talk mode を待つ" \
     "電源投入後、機体が起動しきるまで待つ。" \
     "\033[1m音声案内（Zero Talk mode）が出るまで操作しない。\033[0m" \
     "この間の関節はゼロトルク（FSM 0）で脱力している。数十秒かかる。"

step "3. ① ダンピング（Damping mode）に入れる" \
     "リモコンで \033[1m①\033[0m を選ぶ。関節に粘りが出て、押すと抵抗が返る。" \
     "ここで初めてモータが有効（mode=1）になる。" \
     "\033[1mテレオペや腕の再生をするなら、この状態が要る。\033[0m"

step "4. ② 立位ロック（Locked Standing）にする" \
     "リモコンで \033[1m②\033[0m を選ぶ。脚が伸びて立位で固定される。" \
     "\033[1mここでウィンチを緩め、自分の脚で立っていることを確かめる。\033[0m" \
     "ぐらつくなら吊り上げ直して 1 からやり直す。"

step "5. ⑦ 通常運転（Regular mode / Running mode）にする" \
     "リモコンで \033[1m⑦\033[0m を選ぶ。歩行制御が動きだす。" \
     "ここから前後左右・旋回がリモコンで効く。" \
     "\033[1mまず小さく前後させて、素直に動くことを確かめてから見せる。\033[0m"

_head "見せ終わったら"
cat <<'GUIDE'
   逆の順で下ろす。いきなり電源を切らないこと。

     ⑦ 通常運転  →  ② 立位ロック  →  ① ダンピング  →  電源

   立たせたまま離れない。ダンピングへ落とす前に吊り具で支えること。
GUIDE

_head "このあと"
printf '  実演2（Isaac Sim + Nav2）へ  : bash Demo/02_isaac_nav2.sh\n'
printf '  実演3（LiDAR で計測）へ      : bash Demo/03_lidar.sh\n'
printf '  実演4（Quest でエピソード）  : ⚠️ ① ダンピングに入れ直してから\n'
